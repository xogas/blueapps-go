// 测试 GetBool 函数（True 场景）
func TestGetBoolTrueCase(t *testing.T) {
	tests := []struct {
		key   string
		value string
	}{
		{"TRUE_1", "1"},
		{"TRUE_2", "t"},
		{"TRUE_3", "T"},
		{"TRUE_4", "true"},
		{"TRUE_5", "TRUE"},
		{"TRUE_6", "True"},
	}
	for _, tt := range tests {
		_ = os.Setenv(tt.key, tt.value)
		ret := envx.GetBool(tt.key)
		assert.True(t, ret)
	}
}

